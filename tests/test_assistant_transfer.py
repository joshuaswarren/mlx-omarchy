class StagedReplacement(Base):
    def test_verified_replacement_and_failure_keeps_old_install(self) -> None:
        self.export(out="a.zip")
        self.import_(bundle="a.zip")
        good = (self.dst_home / "assistant" / "imports" / "everyday" / "chat" / "config.json"
                ).read_bytes()
        # second, different verified bundle replaces it
        (self.chat_dir / "config.json").write_bytes('{"v":2}'.encode())
        self.export(out="b.zip")
        self.import_(bundle="b.zip")
        self.assertEqual(
            (self.dst_home / "assistant" / "imports" / "everyday" / "chat" / "config.json"
             ).read_bytes(), b'{"v":2}')
        # corrupt bundle fails verification and leaves b installed untouched
        self.rewrite_zip(self.bundle_path("b.zip"), self.bundle_path("bad.zip"),
                         lambda n, d: d[:-1] + bytes([d[-1] ^ 0xFF])
                         if n.endswith("chat/config.json") else d)
        with self.assertRaises(transfer.VerificationFailed):
            self.import_(bundle="bad.zip")
        self.assertEqual(
            (self.dst_home / "assistant" / "imports" / "everyday" / "chat" / "config.json"
             ).read_bytes(), b'{"v":2}')
        self.assertEqual(good, b"{}")
        self.assertFalse((self.dst_home / "transfer" / "backup").exists())
        self.assertFalse((self.dst_home / "transfer" / "staging").exists())

    def test_reimport_over_existing_creates_swap(self) -> None:
        self.export(out="a.zip")
        first = self.import_(bundle="a.zip")
        second = self.import_(bundle="a.zip")
        self.assertEqual(first["bundle_id"], second["bundle_id"])
        self.assertTrue(
            (self.dst_home / "assistant" / "imports" / "everyday" / "transfer-lock.json").exists()
        )


class UnsafeArchives(Base):
    def _assert_refused(self, bundle: Path, exc=transfer.UnsafeArchive) -> None:
        with self.assertRaises(exc):
            self.import_(bundle=bundle.name)
        self.assertFalse((self.dst_home / "assistant").exists())
        self.assertFalse((self.dst_home / "transfer").exists())

    def build_payload(self) -> dict:
        manifest = self.export()
        with zipfile.ZipFile(self.bundle_path()) as zf:
            return {n: zf.read(n) for n in zf.namelist()}

    def test_traversal_and_absolute_members(self) -> None:
        members = self.build_payload()
        for evil in ("../evil.txt", "/abs/evil.txt", "a/../../evil", r"back\\slash"):
            m = dict(members)
            m[evil] = b"x"
            self.raw_zip(self.bundle_path("evil.zip"), sorted(m.items()))
            self._assert_refused(self.bundle_path("evil.zip"))

    def test_symlink_and_directory_members(self) -> None:
        members = self.build_payload()
        m = dict(members)
        m["everyday/link"] = b"payload"
        self.raw_zip(self.bundle_path("sym.zip"), sorted(m.items()),
                     external_attrs={"everyday/link": (stat.S_IFLNK | 0o644) << 16})
        self._assert_refused(self.bundle_path("sym.zip"))
        m2 = {k: v for k, v in members.items()}
        self.raw_zip(self.bundle_path("dir.zip"), sorted(m2.items()) + [("everyday/dir/", b"")])
        self._assert_refused(self.bundle_path("dir.zip"))

    def test_duplicate_members(self) -> None:
        members = sorted(self.build_payload().items())
        with zipfile.ZipFile(self.bundle_path("dup.zip"), "w", zipfile.ZIP_STORED) as zf:
            for name, data in members + members[-1:]:
                zf.writestr(name, data)
        self._assert_refused(self.bundle_path("dup.zip"))

    def test_member_not_in_manifest_and_size_mismatch(self) -> None:
        members = self.build_payload()
        m = dict(members)
        m["everyday/extra.bin"] = b"sneaky"
        self.raw_zip(self.bundle_path("extra.zip"), sorted(m.items()))
        self._assert_refused(self.bundle_path("extra.zip"))
        # declared size inconsistent with actual member
        m = dict(members)
        victim = "everyday/chat/config.json"
        m[victim] = b"{}" + b"x" * 10
        self.raw_zip(self.bundle_path("size.zip"), sorted(m.items()))
        self._assert_refused(self.bundle_path("size.zip"))

    def test_hash_mismatch(self) -> None:
        manifest = self.export()
        with zipfile.ZipFile(self.bundle_path()) as zf:
            mb = json.loads(zf.read(transfer.MANIFEST_NAME))
        mb["files"]["everyday/chat/config.json"]["sha256"] = "0" * 64
        members = self.build_payload()
        members[transfer.MANIFEST_NAME] = json.dumps(mb).encode()
        self.raw_zip(self.bundle_path("hash.zip"), sorted(members.items()))
        self._assert_refused(self.bundle_path("hash.zip"), transfer.VerificationFailed)

    def test_bomb_total_cap(self) -> None:
        self.export()
        with self.assertRaises(transfer.UnsafeArchive):
            self.import_(max_total_bytes=1024)


