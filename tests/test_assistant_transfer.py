    def _rebuild(self, out: str, *, manifest_fn=None, member_fn=None) -> None:
        members = self._members()
        manifest = json.loads(members[transfer.MANIFEST_NAME])
        if member_fn:
            members = member_fn(members)
            for name, data in members.items():
                if name == transfer.MANIFEST_NAME:
                    continue
                manifest["files"][name] = {"sha256": hashlib.sha256(data).hexdigest(),
                                           "size": len(data)}
            manifest["total_bytes"] = sum(e["size"] for e in manifest["files"].values())
        if manifest_fn:
            manifest = manifest_fn(manifest)
        members[transfer.MANIFEST_NAME] = json.dumps(manifest).encode()
        self.raw_zip(self.bundle_path(out), sorted(members.items()))

