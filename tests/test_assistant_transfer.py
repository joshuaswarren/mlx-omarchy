def make_wheel(dest_dir: Path, name: str, version: str, *, requires=(), modules=(),
               entry_points: dict | None = None,
               tags: str = "py3-none-any") -> Path:
    """Build a real installable wheel with METADATA/WHEEL/RECORD (tiny, no blobs)."""
    import base64

    def b64(data: bytes) -> str:
        return base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()

    dist = f"{name.replace('-', '_')}-{version}"
    files: dict[str, bytes] = {}
    for mod in modules:
        if isinstance(mod, tuple):
            modname, body = mod
        else:
            modname, body = mod, f"VALUE = '{mod}'\n"
        files[f"{modname}.py"] = body.encode()
    if entry_points:
        files[f"{dist}.dist-info/entry_points.txt"] = (
            "[console_scripts]\n"
            + "".join(f"{script} = {target}\n" for script, target in entry_points.items())
        ).encode()
    meta = f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
    meta += "".join(f"Requires-Dist: {r}\n" for r in requires)
    files[f"{dist}.dist-info/METADATA"] = meta.encode()
    files[f"{dist}.dist-info/WHEEL"] = (
        f"Wheel-Version: 1.0\nGenerator: test\nRoot-Is-Purelib: true\nTag: {tags}\n"
    ).encode()
    record_name = f"{dist}.dist-info/RECORD"
    record = "".join(
        f"{path},sha256={b64(data)},{len(data)}\n" for path, data in files.items()
    )
    files[record_name] = (record + f"{record_name},,\n").encode()
    dest_dir.mkdir(parents=True, exist_ok=True)
    wheel = dest_dir / f"{name}-{version}-{tags}.whl"
    with zipfile.ZipFile(wheel, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, data in files.items():
            zf.writestr(path, data)
    return wheel


def unpack_wheel(wheel: Path, site: Path) -> None:
    """Unpack a wheel into a fake site-packages (importlib.metadata reads dist-info)."""
    with zipfile.ZipFile(wheel) as zf:
        zf.extractall(site)


def make_site_with_wheels(root: Path, specs) -> tuple[Path, Path]:
    """Wheel fixtures dir + matching unpacked fake site-packages. Returns (fixtures, site).

    Each spec is (name, version, requires) or (name, version, requires, modules).
    """
    fixtures = root / "fixtures"
    site = root / "site"
    for name, version, requires, *rest in specs:
        modules = rest[0] if rest else ()
        unpack_wheel(make_wheel(fixtures, name, version, requires=requires,
                                modules=modules), site)
    return fixtures, site


def make_fake_pip(script_path: Path, fixtures: Path, omit: str = "") -> list:
    """A stub `pip download --no-deps` that copies fixture wheels for requested pins."""
    script_path.write_text(
        "import os, shutil, sys\n"
        "args = sys.argv[1:]\n"
        "dest = args[args.index('-d') + 1]\n"
        f"fixtures = {str(fixtures)!r}\n"
        f"omit = {omit!r}\n"
        "pins = [a for a in args if '==' in a]\n"
        "for pin in pins:\n"
        "    if omit and pin.startswith(omit):\n"
        "        continue\n"
        "    name = pin.split('==')[0]\n"
        "    for f in os.listdir(fixtures):\n"
        "        if f.startswith(name + '-'):\n"
        "            shutil.copy(os.path.join(fixtures, f), dest)\n"
        "if omit:\n"
        "    sys.stderr.write('ERROR: No matching distribution for ' + omit + '\\n')\n"
        "    raise SystemExit(1)\n"
    )
    return [sys.executable, str(script_path)]


class Base(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.src_home = self.root / "src-home"
        self.dst_home = self.root / "dst-home"
        self.chat_dir = self._model_dir(
            "chat", {"model.safetensors": b"Q" * 4096, "config.json": b"{}", "tokenizer.json": b"[]"}
        )
        self.decision_dir = self._model_dir("decision", {"model.safetensors": b"L" * 2048})
        self.wh = self.root / "wheelhouse"
        self.wh.mkdir()
        (self.wh / WHEEL).write_bytes(WHEEL_BYTES)
        self.lock = {
            "version": 1,
            "pair_id": "everyday",
            "routing_policy": "1",
            "context_tokens": 8192,
            "max_questions": 8,
            "created_at": "2026-09-27T00:00:00+00:00",
            "boot_id": None,
            "started_offline": True,
            "chip": {"arch": ["t6021"]},
            "licenses": {"qwen3.8-2b-4bit": "apache-2.0", "laya-mlx": "apache-2.0"},
            "models": {
                "chat": {
                    "id": "qwen3.8-2b-4bit", "repo": "org/qwen", "revision": "a" * 40,
                    "path": str(self.chat_dir), "weights_bytes": 4096, "kv_bytes_per_token": 128,
                },
                "decision": {
                    "id": "laya-mlx", "repo": "convaiinnovations/laya", "revision": "b" * 40,
                    "path": str(self.decision_dir), "weights_bytes": 2048, "kv_bytes_per_token": 0,
                },
            },
        }
        self.pairs = [{"pair_id": "everyday", "lock": self.lock}]

    def _voice_dir(self, *, corrupt: bool = False) -> Path:
        files = {
            "model.safetensors": b"V" * 4096,
            "config.json": b"{}",
            "speech_tokenizer/model.safetensors": b"T" * 1024,
        }
        pack = self.src_home / "voice" / "qwen3-tts-0.6b-customvoice-4bit"
        for rel, data in files.items():
            path = pack / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(corrupt and rel.endswith("safetensors") and data + b"x" or data)
        manifest = {
            "pack_id": "qwen3-tts-0.6b-customvoice-4bit",
            "repo": "mlx-community/Qwen3-TTS",
            "revision": "c" * 40,
            "license": "apache-2.0",
            "files": {rel: {"bytes": len(d), "sha256": hashlib.sha256(d).hexdigest()}
                      for rel, d in files.items()},
        }
        (pack / "manifest.json").write_text(json.dumps(manifest, indent=1))
        return pack

    def _model_dir(self, role: str, files: dict) -> Path:
        d = self.src_home / "artifacts" / role
        d.mkdir(parents=True)
        for name, data in files.items():
            (d / name).write_bytes(data)
        return d

    def export(self, *, pairs=None, required=(WHEEL,), approved=frozenset({"apache-2.0"}),
               out="bundle.zip", platform=None, voice=(), **kw) -> dict:
        wheels = {}
        for w in required:
            path = self.wh / w
            entry = {"wheel": w, "version": "1.0.0"}
            if path.is_file():
                entry["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
                entry["size"] = path.stat().st_size
            wheels[w.split("-")[0].replace("_", "-").lower()] = entry
        return transfer.export_bundle(
            self.root / out,
            pairs=self.pairs if pairs is None else pairs,
            wheelhouse=self.wh,
            wheels=wheels,
            voice=list(voice),
            approved_licenses=set(approved),
            platform_info=dict(platform or PLAT),
            **kw,
        )

    def bundle_path(self, name="bundle.zip") -> Path:
        return self.root / name

    def import_(self, *, approved=frozenset({"apache-2.0"}), bundle="bundle.zip", **kw) -> dict:
        return transfer.import_bundle(
            self.dst_home, self.bundle_path(bundle), set(approved), platform_info=dict(PLAT), **kw
        )

    def rewrite_zip(self, src: Path, dst: Path, mutate) -> None:
        with zipfile.ZipFile(src) as zin, zipfile.ZipFile(dst, "w", zipfile.ZIP_STORED) as zout:
            for zi in zin.infolist():
                zout.writestr(zi.filename, mutate(zi.filename, zin.read(zi.filename)))

    def raw_zip(self, dst: Path, members, external_attrs=None) -> None:
        with zipfile.ZipFile(dst, "w", zipfile.ZIP_STORED) as zf:
            for name, data in members:
                zi = zipfile.ZipInfo(name)
                zi.external_attr = (external_attrs or {}).get(
                    name, (stat.S_IFREG | 0o644) << 16)
                zf.writestr(zi, data)


class ExportImportRoundtrip(Base):
    def test_roundtrip_restores_artifacts_and_localizes_lock(self) -> None:
        manifest = self.export()
        self.assertTrue(manifest["wheels_complete"])
        result = self.import_()
        imports = self.dst_home / "assistant" / "imports"
        chat = imports / "everyday" / "chat"
        for name, data in [("model.safetensors", b"Q" * 4096), ("config.json", b"{}"),
                           ("tokenizer.json", b"[]")]:
            self.assertEqual((chat / name).read_bytes(), data)
        self.assertEqual(
            (imports / "everyday" / "decision" / "model.safetensors").read_bytes(), b"L" * 2048
        )
        self.assertEqual((imports / "wheels" / WHEEL).read_bytes(), WHEEL_BYTES)
        localized = json.loads((imports / "everyday" / "transfer-lock.json").read_text())
        self.assertEqual(localized["models"]["chat"]["path"], str(chat))
        self.assertEqual(localized["models"]["chat"]["revision"], "a" * 40)
        self.assertEqual(localized["models"]["decision"]["path"],
                         str(imports / "everyday" / "decision"))
        self.assertEqual(localized["licenses"], self.lock["licenses"])
        self.assertEqual(localized["chip"], self.lock["chip"])
        receipt = json.loads((imports / "everyday" / "transfer-receipt.json").read_text())
        self.assertEqual(receipt["bundle_id"], manifest["bundle_id"])
        # staging is cleaned up; source lock untouched
        self.assertFalse((self.dst_home / "transfer" / "staging").exists())
        self.assertFalse(list(self.root.glob("bundle.zip.tmp")))

