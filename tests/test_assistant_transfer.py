class GenerationActivation(unittest.TestCase):
    """Candidates stage beside venv_target; activation is an atomic symlink swap."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.prefix = self.root / "prefix"
        self.target = self.prefix / "venv"

    @staticmethod
    def _wh(root: Path, version: str, value: str) -> Path:
        wh = root / f"wh{version}"
        make_wheel(wh, "pkgc", version,
                   modules=(("pkgc", f"VALUE = '{value}'\n\n"
                               "def main():\n    print(VALUE)\n"),),
                   entry_points={"fake-chat": "pkgc:main"})
        return wh

    def _install(self, wh: Path, version: str) -> None:
        transfer.install_runtime(self.target, wh, requirements={"pkgc": version},
                                 probe_imports=["pkgc"])

    def _run(self, args=None):
        return subprocess.run([str(self.target / "bin" / "fake-chat"), *(args or [])],
                              cwd=self.root, capture_output=True, text=True, timeout=60)

    def _gens(self) -> list[str]:
        return sorted(p.name for p in self.prefix.glob("venv.gen-*"))

    def test_active_install_survives_candidate_staging(self) -> None:
        self._install(self._wh(self.root, "1.0.0", "one"), "1.0.0")
        gen1 = Path(os.path.realpath(self.target))
        self.assertTrue(self.target.is_symlink(), "activated venv must be a symlink")
        staged_seen, proceed = threading.Event(), threading.Event()
        observed: dict = {}
        real_verify = transfer.verify_venv_records

        def spy(venv_path, requirements):
            proc = self._run()
            observed["during"] = (proc.returncode, proc.stdout.strip(),
                                  self.target.is_symlink(),
                                  Path(os.path.realpath(self.target)) == gen1)
            staged_seen.set()
            proceed.wait(30)
            return real_verify(venv_path, requirements)

        outcome: dict = {}

        def work():
            try:
                self._install(self._wh(self.root, "2.0.0", "two"), "2.0.0")
            except BaseException as exc:  # surfaced on the main thread
                outcome["err"] = exc

        with mock.patch.object(transfer, "verify_venv_records", spy):
            worker = threading.Thread(target=work)
            worker.start()
            self.assertTrue(staged_seen.wait(60), "candidate never reached verification")
            # the old install is still exactly what callers see mid-staging
            self.assertEqual(observed["during"], (0, "one", True, True))
            proceed.set()
            worker.join(120)
        self.assertNotIn("err", outcome, getattr(outcome.get("err"), "stderr", None))
        proc = self._run()
        self.assertEqual((proc.returncode, proc.stdout.strip()), (0, "two"))
        self.assertNotEqual(Path(os.path.realpath(self.target)), gen1)
        self.assertFalse(gen1.exists(), "replaced generation must be pruned")
        self.assertEqual(len(self._gens()), 1)

    def test_failed_candidate_leaves_no_partial_target(self) -> None:
        self._install(self._wh(self.root, "1.0.0", "one"), "1.0.0")
        gen1 = Path(os.path.realpath(self.target))
        broken = self._wh(self.root, "2.0.0", "two")
        wheel = next(broken.glob("pkgc-2.0.0-*.whl"))
        data = wheel.read_bytes()
        wheel.write_bytes(data[: len(data) // 2])
        with self.assertRaises(transfer.TransferError):
            self._install(broken, "2.0.0")
        self.assertTrue(self.target.is_symlink())
        self.assertEqual(Path(os.path.realpath(self.target)), gen1)
        proc = self._run()
        self.assertEqual((proc.returncode, proc.stdout.strip()), (0, "one"))
        self.assertEqual(self._gens(), [gen1.name],
                         "failed candidate generation must be removed")
        self.assertEqual([p.name for p in self.prefix.glob(".venv.*")], [])

    def test_legacy_real_dir_migrates_and_rolls_back(self) -> None:
        # a real directory from another installer: migrated to backup at commit
        subprocess.run([sys.executable, "-m", "venv", "--clear", str(self.target)],
                       check=True, capture_output=True, timeout=60)
        self.assertFalse(self.target.is_symlink())
        self._install(self._wh(self.root, "1.0.0", "one"), "1.0.0")
        self.assertTrue(self.target.is_symlink())
        self.assertEqual([p.name for p in self.prefix.glob(".venv.*")],
                         [], "migrated backup must be pruned after success")
        proc = self._run()
        self.assertEqual((proc.returncode, proc.stdout.strip()), (0, "one"))
        # staging failure over a legacy real dir must not touch the target
        self.target.unlink()
        subprocess.run([sys.executable, "-m", "venv", "--clear", str(self.target)],
                       check=True, capture_output=True, timeout=60)
        broken = self._wh(self.root, "9.0.0", "nine")
        wheel = next(broken.glob("pkgc-9.0.0-*.whl"))
        data = wheel.read_bytes()
        wheel.write_bytes(data[: len(data) // 2])
        with self.assertRaises(transfer.TransferError):
            self._install(broken, "9.0.0")
        self.assertFalse(self.target.is_symlink())
        self.assertTrue((self.target / "bin" / "python").exists(),
                        "legacy target must survive a failed staging")

    def test_foreign_symlink_target_refused(self) -> None:
        decoy = self.root / "decoy"
        decoy.mkdir()
        (decoy / "keep").write_bytes(b"keep")
        self.target.parent.mkdir(parents=True)
        self.target.symlink_to(decoy)
        with self.assertRaisesRegex(transfer.TransferError, "outside transfer ownership"):
            self._install(self._wh(self.root, "1.0.0", "one"), "1.0.0")
        self.assertTrue(self.target.is_symlink())
        self.assertEqual(Path(os.readlink(self.target)), decoy)
        self.assertTrue((decoy / "keep").exists(), "foreign target must be untouched")
        self.assertEqual(self._gens(), [], "failed candidate must not linger")

    def test_double_upgrade_prunes_retired_generation(self) -> None:
        self._install(self._wh(self.root, "1.0.0", "one"), "1.0.0")
        self._install(self._wh(self.root, "2.0.0", "two"), "2.0.0")
        self._install(self._wh(self.root, "3.0.0", "three"), "3.0.0")
        proc = self._run()
        self.assertEqual((proc.returncode, proc.stdout.strip()), (0, "three"))
        self.assertEqual(len(self._gens()), 1)


