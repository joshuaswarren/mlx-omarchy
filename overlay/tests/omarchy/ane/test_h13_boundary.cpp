std::string base64_decode(const char* encoded) {
  static const std::string alphabet =
      "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  std::string text(encoded);
  std::vector<uint8_t> decoded;
  int phase = 0;
  uint32_t accumulator = 0;
  for (char c : text) {
    if (c == '\n' || c == '\r' || c == ' ') {
      continue;
    }
    if (c == '=') {
      break;
    }
    size_t value = alphabet.find(c);
    if (value == std::string::npos) {
      break;
    }
    accumulator = (accumulator << 6) | static_cast<uint32_t>(value);
    if (++phase == 4) {
      decoded.push_back(static_cast<uint8_t>((accumulator >> 16) & 0xff));
      decoded.push_back(static_cast<uint8_t>((accumulator >> 8) & 0xff));
      decoded.push_back(static_cast<uint8_t>(accumulator & 0xff));
      phase = 0;
      accumulator = 0;
    }
  }
  // Final unpadded quantum: 3 chars carry 2 bytes, 2 chars carry 1.
  if (phase == 3) {
    decoded.push_back(static_cast<uint8_t>((accumulator >> 10) & 0xff));
    decoded.push_back(static_cast<uint8_t>((accumulator >> 2) & 0xff));
  } else if (phase == 2) {
    decoded.push_back(static_cast<uint8_t>((accumulator >> 4) & 0xff));
  }
  return std::string(decoded.begin(), decoded.end());
}

// Same temp-directory pattern as test_bundle.cpp.
class TempDir {
 public:
  TempDir() {
    namespace fs = std::filesystem;
    fs::path base = fs::temp_directory_path() / "mlx-omarchy-ane-h13-boundary";
    fs::create_directories(base);
    for (int attempt = 0; attempt < 64; ++attempt) {
      fs::path candidate =
          base / ("case-" + std::to_string(attempt) + "-" +
                  std::to_string(::getpid()));
      std::error_code error;
      if (fs::create_directory(candidate, error) && !error) {
        path_ = candidate;
        return;
      }
    }
    throw std::runtime_error("cannot create temp directory");
  }
  ~TempDir() {
    std::error_code error;
    std::filesystem::remove_all(path_, error);
  }
  const std::filesystem::path& path() const {
    return path_;
  }

 private:
  std::filesystem::path path_;
};

void write_file(const std::filesystem::path& path, const std::string& content) {
  std::ofstream out(path, std::ios::binary | std::ios::trunc);
  out << content;
  REQUIRE(out.good());
}

// Writes one program payload and returns the bundle directory containing
// only manifest.json and that payload.
std::filesystem::path write_program_bundle(
    const TempDir& temp,
    const char* program_base64,
    const char* program_path,
    const std::string& manifest_json) {
  namespace fs = std::filesystem;
  static int counter = 0;
  fs::path dir = temp.path() / ("bundle-" + std::to_string(counter++));
  fs::create_directories(dir);
  write_file(dir / program_path, base64_decode(program_base64));
  write_file(dir / "manifest.json", manifest_json);
  return dir;
}

