// A format-valid firmware range for cases whose purpose requires manifest
// parsing to complete (payload verification). The validator cannot check
// the range's semantics (§8.7) — that is exactly why firmware identity
// stays an operator-verified required input. Diagnostic value only.
std::string with_diagnostic_firmware(std::string manifest) {
  const std::string empty = "\"firmware\": {\"min\": \"\", \"max\": \"\"},";
  const std::string range = "\"firmware\": {\"min\": \"0.0\", \"max\": \"0.0\"},";
  REQUIRE(manifest.find(empty) != std::string::npos);
  manifest.replace(manifest.find(empty), empty.size(), range);
  return manifest;
}

std::string load_error(const std::filesystem::path& dir) {
  try {
    load_bundle(dir);
  } catch (const AneBundleNotFound& error) {
    return std::string("not_found: ") + error.what();
  } catch (const std::exception& error) {
    return error.what();
  }
  return {};
}

